"""Generates src/shared/homophones.js: common English words that sound alike.

    python tools/make-homophones.py CMUDICT_DICT SCOWL_FINAL_DIR

CMUDICT_DICT: cmudict.dict from https://github.com/cmusphinx/cmudict
(BSD-2-Clause). SCOWL_FINAL_DIR: the final/ folder of SCOWL 2020.12.07
(http://wordlist.aspell.net/, permissive licence); its size levels stand in
for how common a word is. Notices for both are in THIRD_PARTY_NOTICES.md.

A speech model can't tell eye from I or tail from tale, and the extension
may not use the question to decide (F4), so normalisation offers the other
spelling as a choice instead (src/shared/normalize.js). Two words are
homophones when any of their CMUdict pronunciations match, ignoring stress.
Both must be common (SCOWL level <= MAX_LEVEL), plain lower-case letters.
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

MAX_LEVEL = 35
PER_WORD = 2  # at most this many alternatives per word, commonest first
OUT = Path(__file__).resolve().parent.parent / "src/shared/homophones.js"


def levels(final_dir):
    level = {}
    for f in Path(final_dir).iterdir():
        m = re.fullmatch(r"(english|american|british)-words\.(\d+)", f.name)
        if not m or int(m.group(2)) > MAX_LEVEL:
            continue
        for w in f.read_text(encoding="latin-1").split():
            if re.fullmatch(r"[a-z]+", w):
                level[w] = min(level.get(w, 99), int(m.group(2)))
    # "I" is filed with the capitalised words; speech models write it for "eye".
    level["i"] = 10
    return level


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmudict")
    ap.add_argument("scowl_final")
    args = ap.parse_args()
    level = levels(args.scowl_final)
    by_sound = defaultdict(set)
    for line in Path(args.cmudict).read_text(encoding="utf-8").splitlines():
        word, *phones = line.split("#")[0].split()
        word = re.sub(r"\(\d+\)$", "", word)
        if word in level:
            by_sound[" ".join(re.sub(r"\d", "", p) for p in phones)].add(word)
    table = defaultdict(set)
    for words in by_sound.values():
        for w in words:
            table[w] |= words - {w}
    table = {
        w: sorted(alts, key=lambda a: (level[a], a))[:PER_WORD]
        for w, alts in sorted(table.items()) if alts
    }
    body = json.dumps(table, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Generated by tools/make-homophones.py from CMUdict (BSD-2-Clause) and\n"
        "// SCOWL (see THIRD_PARTY_NOTICES.md). Do not edit by hand.\n"
        "// word -> common words that sound the same, commonest first.\n"
        f"(function (WKV) {{\n  'use strict';\n  WKV.homophones = {body};\n}})(globalThis.WKV = globalThis.WKV || {{}});\n",
        encoding="utf-8",
    )
    print(f"{len(table)} words -> {OUT}")


if __name__ == "__main__":
    main()
